def load_audited_data():
    """Downloads the audited production dataset from S3 for monitoring and retraining."""
    local_file = Path(AUDITED_FILE)
    local_file.parent.mkdir(parents=True, exist_ok=True)
    if local_file.exists():
        logger.info("\033[1;33m[CLEANUP] Removing existing file %s to prevent S3Hook locks.\033[0m", local_file.name)
        local_file.unlink()
    logger.info("\033[1;34m[LOAD] Downloading audited file from S3...\033[0m")
    hook.download_file(
        bucket_name=S3_BUCKET,
        key=AUDITED_KEY,
        local_path=str(local_file.parent),
        preserve_file_name=True,
        use_autogenerated_subdir=False
    )
    logger.info("\033[1;32m[SUCCESS] Audited file successfully downloaded.\033[0m")
    return AUDITED_FILE