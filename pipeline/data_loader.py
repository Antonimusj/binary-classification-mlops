import logging
from pathlib import Path
from config.settings import (
    S3_BUCKET, TRAIN_KEY, REAL_DATA_KEY, INFERENCE_KEY,
    COLUMNS_KEY, MODEL_KEY, TRAIN_RAW_FILE, REAL_DATA,
    INFERENCE_RAW_FILE, COLUMNS_FILE, BEST_MODEL_FILE, AUDITED_KEY, AUDITED_FILE
)
from pipeline.utils import s3_conection

logger = logging.getLogger(__name__)
hook = s3_conection()


def load_training_data():
    """Downloads the raw training dataset from S3 if not already present locally."""
    Path(TRAIN_RAW_FILE).parent.mkdir(parents=True, exist_ok=True)
    if Path(TRAIN_RAW_FILE).exists() and Path(TRAIN_RAW_FILE).stat().st_size > 0:
        logger.info("\033[1;33m[LOAD] Local training dataset already exists. Skipping download.\033[0m")
        return TRAIN_RAW_FILE
    logger.info("\033[1;34m[LOAD] Downloading original training dataset from S3...\033[0m")
    hook.download_file(
        bucket_name=S3_BUCKET,
        key=TRAIN_KEY,
        local_path=str(Path(TRAIN_RAW_FILE).parent),
        preserve_file_name=True,
        use_autogenerated_subdir=False
    )
    logger.info("\033[1;32m[SUCCESS] Training dataset successfully downloaded.\033[0m")
    return TRAIN_RAW_FILE


